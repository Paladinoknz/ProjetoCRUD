    private void jBregistar_filmeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBregistar_filmeActionPerformed
        // TODO add your handling code here:
       try{
           
        CadastrarDiretor cd = new CadastrarDiretor(); CadastrarGenero cg = new CadastrarGenero();
        CadastrarProdutora cp = new CadastrarProdutora(); CadastrarFilme cf = new CadastrarFilme();
        
        Diretor d = new Diretor(); Genero g = new Genero();  Produtora p = new Produtora(); Filme f = new Filme();
        
        
     
        //aqui pegamos o que o usuario digitou nas caixas livres e setamos nos objetos 
        p.setPais(jTpais_produtora.getText());
        p.setNome(jTnome_produtora.getText());
        g.setNome(jCgeneros.getSelectedItem().toString());
        f.setDescricao(jTdescricao_filme.getText());
        d.setNome(jTnome_diretor.getText());
        d.setNacionaldade(jTnacionalidade.getText());
        
        
        //nessa parte eu capturo o retorno do metodo inserir, no caso
        //o retorno é o ID que foi registrado no banco de dados
       int idGeradoCd = cd.inserir(d);
       int idGeradoCg = cg.PesquisarRegistro(g);
       int idGeradoCp = cp.inserir(p);
        
       
       //pego o ID que foi registrado no banco de dados e coloco como
       //id aqui no meu objeto
        d.setId_diretor(idGeradoCd);
        g.setId_genero(idGeradoCg);
        p.setId_produtora(idGeradoCp);
        
        
        f.setTitulo(jTnome_filme.getText());
        f.setAno_lancamento(Integer.valueOf(jTano_lancamento.getText()));
        f.setDuracao_min(Integer.valueOf(jTduracao_filme.getText()));
        f.setId_genero(g.getId_genero());
        f.setId_diretor(d.getId_diretor());
        f.setId_produtora(p.getId_produtora());
        f.setId_usuario(usuarioLogado.getId_usuario());
          
        
        
      
        
        cf.inserir(f);
           
       }catch (Exception e) {
        
             JOptionPane.showMessageDialog(this,"Erro de : " + e.getMessage());
        }
        
        
       
        
        
        
        
        
    }//GEN-LAST:event_jBregistar_filmeActionPerformed

